// Icon renders a named outline icon. Unknown names render nothing.
func Icon(name string) templ.Component {
	return templ.ComponentFunc(func(_ context.Context, w io.Writer) error {
		if name == "github" {
			_, err := io.WriteString(w, `<svg viewBox="0 0 16 16" fill="currentColor" aria-hidden="true">`+githubMark+`</svg>`)
			return err
		}
		body, ok := icons[name]
		if !ok {
			return nil
		}
		_, err := fmt.Fprintf(w, `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">%s</svg>`, body)
		return err
	})
}
