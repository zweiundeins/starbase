package commands

import (
	"encoding/json"
	"errors"
	"regexp"
	"time"

	"github.com/zweiundeins/lith/writer"

	"starbase/internal/model"
)

const (
	MaxSnippetBytes = 64 << 10
	MaxSnippetFiles = 8
)

var (
	SnippetIDRe   = regexp.MustCompile(`^[A-Za-z0-9]{8}$`)
	snippetFileRe = regexp.MustCompile(`^[a-z0-9][a-z0-9._-]{0,40}\.(js|html|css)$`)
)

// MaxSnippetStore caps all snippets together: anyone may save, and the
// disk may be shared with other services. (A variable for tests.)
var MaxSnippetStore int64 = 256 << 20

// The refusals of a save, which the tab's row records and the page shows.
const (
	RefusedSnippetSize = "This code is over 64 KB, the most a snippet holds. Make it smaller, then save again."
	RefusedStoreFull   = "Saving is paused: the snippet storage is full. Try again later."
)

// SaveSnippet stores playground code under a new, immutable id and shows
// the share link in the saving tab, or why it was refused.
type SaveSnippet struct {
	SID, TabID string
	ID         string // generated by the handler
	Files      map[string]string
	Component  string // optional catalog slug
	UserID     int64  // 0 when anonymous
}

func (c SaveSnippet) Validate() error {
	if err := validTab(c.SID, c.TabID); err != nil {
		return err
	}
	if !SnippetIDRe.MatchString(c.ID) {
		return errors.New("bad snippet id")
	}
	if len(c.Files) == 0 || len(c.Files) > MaxSnippetFiles {
		return errors.New("a snippet has 1 to 8 files")
	}
	for name := range c.Files {
		if !snippetFileRe.MatchString(name) {
			return errors.New("bad file name " + name)
		}
	}
	return nil
}

// Apply touches the saving tab only: no other page shows a new snippet.
// Code over MaxSnippetBytes and a full store are refusals in the tab's row.
func (c SaveSnippet) Apply(tx *writer.Tx) error {
	tx.Touch(TabTopic(c.TabID))
	refuse := func(msg string) error {
		return updateTab(tx, c.SID, c.TabID, model.TabState{}, func(st *model.TabState) {
			st.ShareRefusal = msg
			st.ShareRev++
		})
	}
	size := 0
	for _, body := range c.Files {
		size += len(body)
	}
	if size > MaxSnippetBytes {
		return refuse(RefusedSnippetSize)
	}
	files, err := json.Marshal(c.Files)
	if err != nil {
		return err
	}
	var comp, user any
	if c.Component != "" {
		comp = c.Component
	}
	if c.UserID != 0 {
		user = c.UserID
	}
	res, err := tx.Exec(`UPDATE snippet_stats SET bytes = bytes + ? WHERE id = 1 AND bytes + ? <= ?`,
		len(files), len(files), MaxSnippetStore)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return refuse(RefusedStoreFull)
	}
	if _, err := tx.Exec(`INSERT INTO snippets (id, files, component, user_id, created_at) VALUES (?, ?, ?, ?, ?)`,
		c.ID, string(files), comp, user, time.Now().Unix()); err != nil {
		return err
	}
	return updateTab(tx, c.SID, c.TabID, model.TabState{}, func(st *model.TabState) {
		st.PlaygroundShare = c.ID
		st.ShareRefusal = ""
		st.ShareRev++
	})
}
